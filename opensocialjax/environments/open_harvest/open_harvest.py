def paint_apple_tile(img, hue=0, stage=1):
    """Apple in the patch's hue; stage 0 small and green-tinted, 1 full colour, 2 dull/brown."""
    base = APPLE_HUE_RGB[hue]
    if stage == 0:
        col = tuple(int(0.55 * c + 0.45 * g) for c, g in zip(base, (120, 190, 90))); r = 0.24
    elif stage == 1:
        col = base; r = 0.30
    else:
        col = tuple(int(0.6 * c + 0.4 * b) for c, b in zip(base, (110, 80, 50))); r = 0.30
    rim = tuple(max(0, int(c * 0.6)) for c in col)
    fill_coords(img, point_in_circle(0.5, 0.54, r + 0.05), rim)
    fill_coords(img, point_in_circle(0.5, 0.54, r), col)
    fill_coords(img, point_in_rect(0.47, 0.53, 0.14, 0.30), (70, 140, 60))
    fill_coords(img, point_in_circle(0.41, 0.45, 0.06), (245, 235, 225))


