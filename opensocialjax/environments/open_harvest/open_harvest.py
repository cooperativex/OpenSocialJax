        def combine_channels(
                grid: jnp.ndarray,
                agent: int,
                angles: jnp.ndarray,
                agent_pickups: jnp.ndarray,
                state: State,
            ):
            '''
            Function to enforce symmetry in observations & generate final
            feature representation; current agent is permuted to first 
            position in the feature dimension.
            
            Args:
                - grid: jax ndarray of current agent's obs grid
                - agent: int, an index indicating current agent number
                - angles: jnp.ndarray of current agents' relative orientation
                in current agent's obs grid
                - agent_pickups: jnp.ndarray of agents able to interact
                - state: State, the env state obj
            Returns:
                - grid with current agent [x] permuted to 1st position (after
                the first 4 "Items" features, so 5th position overall) in the
                feature dimension, "other" [x] agent 2nd, angle [x, x, x, x]
                3rd, pick-up [x] bool 4th, inventory [x, x] 5th, frozen [x]
                6th, for a final obs grid of shape (5, 5, 14) (additional 4
                one-hot places for 5 possible items)
            '''
            def move_and_collapse(
                    x: jnp.ndarray,
                    angle: jnp.ndarray,
                ) -> jnp.ndarray:

                # get agent's one-hot
                agent_element = jnp.array([jnp.int8(x[agent])])

                # mask to check if any other agent exists there
                mask = x[len(Items)-1:] > 0

                # does an agent exist which is not the subject?
                other_agent = jnp.int8(
                    jnp.logical_and(
                        jnp.any(mask),
                        jnp.logical_not(
                            agent_element
                        )
                    )
                )

                # what is the class of the item in cell
                item_idx = jnp.where(
                    x,
                    size=1
                )[0]

                # check if agent is frozen and can observe inventories
                show_inv_bool = jnp.logical_and(
                        state.freeze[
                            agent-len(Items)
                        ].max(axis=-1) > 0,
                        item_idx >= len(Items)
                )

                show_inv_idxs = jnp.where(
                    state.freeze[agent],
                    size=12, # since, in a setting where simultaneous interac-
                    fill_value=-1 # -tions can happen, only a max of 12 can
                )[0] # happen at once (zap logic), regardless of pop size

                inv_to_show = jnp.where(
                    jnp.logical_or(
                        jnp.logical_and(
                            show_inv_bool,
                            jnp.isin(item_idx-len(Items), show_inv_idxs),
                        ),
                        agent_element
                    ),
                    state.agent_invs[item_idx - len(Items)],
                    jnp.array([0, 0], dtype=jnp.int8)
                )[0]

                # check if agent is not the subject & is frozen & therefore
                # not possible to interact with
                frozen = jnp.where(
                    other_agent,
                    state.freeze[
                        item_idx-len(Items)
                    ].max(axis=-1) > 0,
                    0
                )

                # get pickup/inv info
                pick_up_idx = jnp.where(
                    jnp.any(mask),
                    jnp.nonzero(mask, size=1)[0],
                    jnp.int8(-1)
                )
                picked_up = jnp.where(
                    pick_up_idx > -1,
                    agent_pickups[pick_up_idx],
                    jnp.int8(0)
                )

                # build extension
                extension = jnp.concatenate(
                    [
                        agent_element,
                        other_agent,
                        angle,
                        picked_up,
                        inv_to_show,
                        frozen
                    ],
                    axis=-1
                )

                # build final feature vector
                final_vec = jnp.concatenate(
                    [x[:len(Items)-1], extension],
                    axis=-1
                )

                return final_vec

            new_grid = jax.vmap(
                jax.vmap(
                    move_and_collapse
                )
            )(grid, angles)
            return new_grid
        
        def check_relative_orientation(
                agent: int,
                agent_locs: jnp.ndarray,
                grid: jnp.ndarray
            ) -> jnp.ndarray:
            '''
            Check's relative orientations of all other agents in view of
            current agent.
            
            Args:
                - agent: int, an index indicating current agent number
                - agent_locs: jax ndarray of agent locations (x, y, direction)
                - grid: jax ndarray of current agent's obs grid
                
            Returns:
                - grid with 1) int -1 in places where no agent exists, or
                where the agent is the current agent, and 2) int in range
                0-3 in cells of opposing agents indicating relative
                orientation to current agent.
            '''
            # we decrement by num of Items when indexing as we incremented by
            # 5 in constructor call (due to 5 non-agent Items enum & locations
            # are indexed from 0)
            idx = agent - len(Items)
            agents = jnp.delete(
                self._agents,
                idx,
                assume_unique_indices=True
            )
            curr_agent_dir = agent_locs[idx, 2]

            def calc_relative_direction(cell):
                cell_agent = cell - len(Items)
                cell_direction = agent_locs[cell_agent, 2]
                return (cell_direction - curr_agent_dir) % 4

            angle = jnp.where(
                jnp.isin(grid, agents),
                jax.vmap(calc_relative_direction)(grid),
                -1
            )

            return angle
        
        def rotate_grid(agent_loc: jnp.ndarray, grid: jnp.ndarray) -> jnp.ndarray:
            '''
            Rotates agent's observation grid k * 90 degrees, depending on agent's
            orientation.

            Args:
                - agent_loc: jax ndarray of agent's x, y, direction
                - grid: jax ndarray of agent's obs grid

            Returns:
                - jnp.ndarray of new rotated grid.

            '''
            grid = jnp.where(
                agent_loc[2] == 1,
                jnp.rot90(grid, k=1, axes=(0, 1)),
                grid,
            )
            grid = jnp.where(
                agent_loc[2] == 2,
                jnp.rot90(grid, k=2, axes=(0, 1)),
                grid,
            )
            grid = jnp.where(
                agent_loc[2] == 3,
                jnp.rot90(grid, k=3, axes=(0, 1)),
                grid,
            )

            return grid

        def _get_obs_point(agent_loc: jnp.ndarray) -> jnp.ndarray:
            '''
            Obtain the position of top-left corner of obs map using
            agent's current location & orientation.

            Args: 
                - agent_loc: jnp.ndarray, agent x, y, direction.
            Returns:
                - x, y: ints of top-left corner of agent's obs map.
            '''
            
            x, y, direction = agent_loc

            x, y = x + self.PADDING, y + self.PADDING

            x = x - (self.OBS_SIZE // 2)
            y = y - (self.OBS_SIZE // 2)


            x = jnp.where(direction == 0, x + (self.OBS_SIZE//2)-1, x)
            y = jnp.where(direction == 0, y, y)

            x = jnp.where(direction == 1, x, x)
            y = jnp.where(direction == 1, y + (self.OBS_SIZE//2)-1, y)


            x = jnp.where(direction == 2, x - (self.OBS_SIZE//2)+1, x)
            y = jnp.where(direction == 2, y, y)


            x = jnp.where(direction == 3, x, x)
            y = jnp.where(direction == 3, y - (self.OBS_SIZE//2)+1, y)


            return x, y

        def _get_obs(state: State) -> jnp.ndarray:
            '''
            Obtain the agent's observation of the grid.

            Args: 
                - state: State object containing env state.
            Returns:
                - jnp.ndarray of grid observation.
            '''
            # create state
            grid = jnp.pad(
                state.grid,
                ((self.PADDING, self.PADDING), (self.PADDING, self.PADDING)),
                constant_values=Items.wall,
            )

            # obtain all agent obs-points
            agent_start_idxs = jax.vmap(_get_obs_point)(state.agent_locs)

            dynamic_slice = partial(
                jax.lax.dynamic_slice,
                operand=grid,
                slice_sizes=(self.OBS_SIZE, self.OBS_SIZE)
            )

            # obtain agent obs grids
            grids = jax.vmap(dynamic_slice)(start_indices=agent_start_idxs)

            # rotate agent obs grids
            grids = jax.vmap(rotate_grid)(state.agent_locs, grids)

            angles = jax.vmap(
                check_relative_orientation,
                in_axes=(0, None, 0)
            )(
                self._agents,
                state.agent_locs,
                grids
            )

            angles = jax.nn.one_hot(angles, 4)

            # one-hot (drop first channel as its empty blocks)
            grids = jax.nn.one_hot(
                grids - 1,
                num_agents + len(Items) - 1, # will be collapsed into a
                dtype=jnp.int8 # [Items, self, other, extra features] representation
            )

            # check agents that can interact
            inventory_sum = jnp.sum(state.agent_invs, axis=-1)
            agent_pickups = jnp.where(
                inventory_sum > INTERACT_THRESHOLD,
                True,
                False
            )

            # make index len(Item) always the current agent
            # and sum all others into an "other" agent
            grids = jax.vmap(
                combine_channels,
                in_axes=(0, 0, 0, None, None)
            )(
                grids,
                self._agents,
                angles,
                agent_pickups,
                state
            )

            return grids

        def _interact(
            key: jnp.ndarray, state: State, actions: jnp.ndarray
        ) -> Tuple[jnp.ndarray, jnp.ndarray, State, jnp.ndarray]:
            '''
            Main interaction logic entry point.

            Args:
                - key: jax key for randomisation.
                - state: State env state object.
                - actions: jnp.ndarray of actions taken by agents.
            Returns:
                - (jnp.ndarray, State, jnp.ndarray) - Tuple where index 0 is
                the array of rewards obtained, index 2 is the new env State,
                and index 3 is the new freeze penalty matrix.
            '''
            # if interact
            zaps = jnp.isin(actions,
                jnp.array(
                    [
                        Actions.zap_forward,
                        # Actions.zap_ahead
                    ]
                )
            )

            interact_idx = jnp.int16(Items.interact)

            # remove old interacts
            state = state.replace(grid=jnp.where(
                state.grid == interact_idx, jnp.int16(Items.empty), state.grid))


            def check_valid_zap(t, i):
                '''
                Check target agent exists, isn't frozen, can interact, and
                is not the zapping-agent's self.
                '''
                agnt_bool = jnp.isin(state.grid[t[0], t[1]], self._agents)
                self_bool = state.grid[t[0], t[1]] != i
            
                return jnp.logical_and(agnt_bool, self_bool)

            # check 1 ahead
            clip_row = partial(jnp.clip, a_min=0, a_max=self.GRID_SIZE_ROW - 1)
            clip_col = partial(jnp.clip, a_min=0, a_max=self.GRID_SIZE_COL - 1)

            one_step_targets = jax.vmap(
                lambda p: p + STEP[p[2]]
            )(state.agent_locs)

            # one_step_targets = jax.vmap(clip)(one_step_targets)
            # one_step_targets[:,0] = jax.vmap(clip_row)(one_step_targets[:,0])
            # one_step_targets[:,1] = jax.vmap(clip_col)(one_step_targets[:,1])

            one_step_interacts = jax.vmap(
                check_valid_zap
            )(t=one_step_targets, i=self._agents)

            # check 2 ahead
            two_step_targets = jax.vmap(
                lambda p: p + 2*STEP[p[2]]
            )(state.agent_locs)

            # two_step_targets = jax.vmap(clip)(two_step_targets)
            # two_step_targets[:,0] = jax.vmap(clip_row)(two_step_targets[:,0])
            # two_step_targets[:,1] = jax.vmap(clip_col)(two_step_targets[:,1])

            two_step_interacts = jax.vmap(
                check_valid_zap
            )(t=two_step_targets, i=self._agents)

            # check forward-right & manually check out-of-bounds
            target_right = jax.vmap(
                lambda p: p + STEP[p[2]] + STEP[(p[2] + 1) % 4]
            )(state.agent_locs)

            right_oob_check = jax.vmap(
                lambda t: jnp.logical_or(
                    jnp.logical_or((t[0] > self.GRID_SIZE_ROW - 1).any(), (t[1] > self.GRID_SIZE_COL - 1).any()),
                    (t < 0).any(),
                )
            )(target_right)

            target_right = jnp.where(
                right_oob_check[:, None],
                one_step_targets,
                target_right
            )

            right_interacts = jax.vmap(
                check_valid_zap
            )(t=target_right, i=self._agents)

            # check forward-left & manually check out-of-bounds
            target_left = jax.vmap(
                lambda p: p + STEP[p[2]] + STEP[(p[2] - 1) % 4]
            )(state.agent_locs)

            left_oob_check = jax.vmap(
                lambda t: jnp.logical_or(
                    jnp.logical_or((t[0] > self.GRID_SIZE_ROW - 1).any(), (t[1] > self.GRID_SIZE_COL - 1).any()),
                    (t < 0).any(),
                )
            )(target_left)

            target_left = jnp.where(
                left_oob_check[:, None],
                one_step_targets,
                target_left
            )

            left_interacts = jax.vmap(
                check_valid_zap
            )(t=target_right, i=self._agents)


            # one_step_targets_exd = jnp.expand_dims(one_step_targets, axis=0)
            # two_step_targets_exd = jnp.expand_dims(two_step_targets, axis=0)
            # target_right_exd = jnp.expand_dims(target_right, axis=0)
            # target_left_exd = jnp.expand_dims(target_left, axis=0)


            # A beam cell outside the grid hits nothing. Without this, a negative index wraps to the far side of the
            # map (firing north from the top rows hit the bottom rows) and a too-large one clamps onto the edge. Park
            # such targets far out of range, where scatters drop them, and mask them out of every hit test.
            def _in_grid(t):
                return (t[:, 0] >= 0) & (t[:, 0] < self.GRID_SIZE_ROW) & (t[:, 1] >= 0) & (t[:, 1] < self.GRID_SIZE_COL)
            _off = jnp.array([self.GRID_SIZE_ROW + 100, self.GRID_SIZE_COL + 100, 0], dtype=one_step_targets.dtype)
            one_ok, two_ok, right_ok, left_ok = (_in_grid(t) for t in (one_step_targets, two_step_targets, target_right, target_left))
            one_step_targets = jnp.where(one_ok[:, None], one_step_targets, _off)
            two_step_targets = jnp.where(two_ok[:, None], two_step_targets, _off)
            target_right = jnp.where(right_ok[:, None], target_right, _off)
            target_left = jnp.where(left_ok[:, None], target_left, _off)
            beam_in_grid = jnp.concatenate((one_ok, two_ok, right_ok, left_ok), 0)

            all_zaped_locs = jnp.concatenate((one_step_targets, two_step_targets, target_right, target_left), 0)
            # zaps_3d = jnp.stack([zaps, zaps, zaps], axis=-1)

            zaps_4_locs = jnp.concatenate((zaps, zaps, zaps, zaps), 0) & beam_in_grid


            # all_zaped_locs = jax.vmap(filter_zaped_locs)(all_zaped_locs)

            def zaped_gird(a, z):
                return jnp.where(z, state.grid[a[0], a[1]], -1)

            all_zaped_gird = jax.vmap(zaped_gird)(all_zaped_locs, zaps_4_locs)
            

            def check_reborn_player(a):
                return jnp.isin(a, all_zaped_gird)
            
            reborn_players = jax.vmap(check_reborn_player)(self._agents)
            # jax.debug.print("reborn_players {reborn_players} 🤯", reborn_players=reborn_players)

            # all interacts = whether there is an agent at target & whether
            # agent is not frozen already & is qualified to interact
            # all_interacts = jnp.concatenate(
            #     [
            #         jnp.expand_dims(one_step_interacts, axis=-1),
            #         jnp.expand_dims(two_step_interacts, axis=-1),
            #         jnp.expand_dims(right_interacts, axis=-1),
            #         jnp.expand_dims(left_interacts, axis=-1)
            #     ],
            #     axis=-1
            # )
            # jax.debug.print("all_interacts {all_interacts} 🤯", all_interacts=all_interacts)

            # def check_reborn_players(i):
            #     return jnp.any(all_interacts[i,:] == True)
            
            # exists_vector = jax.vmap(check_reborn_players)(self._agents-6)

            # reborn_players = jnp.where(exists_vector is True, self._agents, -1)


            # interact_idxs = jnp.clip(actions - Actions.zap_forward, 0, 3)

            # all_interacts = all_interacts[jnp.arange(all_interacts.shape[0]), interact_idxs]# * zaps * agent_pickups * (state.freeze.max(axis=-1) <= 0)

            # update grid with all zaps
            aux_grid = jnp.copy(state.grid)

            o_items = jnp.where(
                        state.grid[
                            one_step_targets[:, 0],
                            one_step_targets[:, 1]
                        ],
                        state.grid[
                            one_step_targets[:, 0],
                            one_step_targets[:, 1]
                        ],
                        interact_idx
                    )

            t_items = jnp.where(
                        state.grid[
                            two_step_targets[:, 0],
                            two_step_targets[:, 1]
                        ],
                        state.grid[
                            two_step_targets[:, 0],
                            two_step_targets[:, 1]
                        ],
                        interact_idx
                    )

            r_items = jnp.where(
                        state.grid[
                            target_right[:, 0],
                            target_right[:, 1]
                        ],
                        state.grid[
                            target_right[:, 0],
                            target_right[:, 1]
                        ],
                        interact_idx
                    )

            l_items = jnp.where(
                        state.grid[
                            target_left[:, 0],
                            target_left[:, 1]
                        ],
                        state.grid[
                            target_left[:, 0],
                            target_left[:, 1]
                        ],
                        interact_idx
                    )

            qualified_to_zap = zaps.reshape(-1)
            # jax.debug.print("qualified_to_zap {qualified_to_zap} 🤯", qualified_to_zap=qualified_to_zap)
            # update grid
            def update_grid(a_i, t, i, grid):
                return grid.at[t[:, 0], t[:, 1]].set(
                    jax.vmap(jnp.where)(
                        a_i,
                        i,
                        aux_grid[t[:, 0], t[:, 1]]
                    )
                )
            # def update_grid(a_i, t, i, grid):
            #     return grid.at[t[:, 0], t[:, 1]].set(2)


            # jax.debug.print("one_step_targets {one_step_targets} 🤯", one_step_targets=one_step_targets)
            aux_grid = update_grid(qualified_to_zap, one_step_targets, o_items, aux_grid)
            aux_grid = update_grid(qualified_to_zap, two_step_targets, t_items, aux_grid)
            aux_grid = update_grid(qualified_to_zap, target_right, r_items, aux_grid)
            aux_grid = update_grid(qualified_to_zap, target_left, l_items, aux_grid)

            # jax.debug.print("aux_grid {aux_grid} 🤯", aux_grid=aux_grid)
            state = state.replace(
                grid=jnp.where(
                    jnp.any(zaps),
                    aux_grid,
                    state.grid
                )
            )


            return reborn_players, state

        def get_current_s_interest(timestep):
            """Calculate current s_interest based on timestep and schedule."""
            if self.s_interest_schedule is None:
                return self.s_interest

            # Calculate which phase we're in using JAX operations
            phase = timestep // self.s_interest_change_every
            phase_idx = phase % self.s_interest_schedule.shape[0]
            return self.s_interest_schedule[phase_idx]

        def _step(
            key: chex.PRNGKey,
            state: State,
            actions: jnp.ndarray,
            timestep: int = 0
        ):
            """Step the environment."""
            # actions = self.action_set.take(indices=jnp.array([actions["0"], actions["agent_1"]]))
            actions = jnp.array(actions)

            zap_frozen = state.zap_wait > 0                      # sent back by a beam: off the game for a few steps
            actions = jnp.where(zap_frozen, jnp.asarray(Actions.stay, actions.dtype), actions)
            actions = jnp.where((state.zap_cd > 0) & (actions == Actions.zap_forward),
                                jnp.asarray(Actions.stay, actions.dtype), actions)   # beam still cooling down

            # freeze check
            # actions = jnp.where(
            #     state.freeze.max(axis=-1) > 0,
            #     Actions.stay,
            #     actions
            # )

            # regrow apple (vanilla neighbour counting; any hue/stage counts as an apple)
            grid_apple = state.grid
            ga = is_apple(grid_apple)
            rate_idx, order = decode_harvest_ruleset(state.rule_encoding, self.num_hues)
            cell_rate = self.RATE_TABLE[rate_idx[state.cell_hues], state.last_stage]   # (num_apple_cells,): speed set by the stage the last apple left at

            def count_apple(apple_locs):

                apple_nums = jnp.where((ga[apple_locs[0]-1, apple_locs[1]]) & (apple_locs[0]-1 >=0), 1, 0) + \
                                jnp.where((ga[apple_locs[0]+1, apple_locs[1]]) & (apple_locs[0]+1 < self.GRID_SIZE_ROW), 1, 0) + \
                                jnp.where((ga[apple_locs[0], apple_locs[1]-1]) & (apple_locs[1]-1 >=0), 1, 0) + \
                                jnp.where((ga[apple_locs[0], apple_locs[1]+1]) & (apple_locs[1]+1 < self.GRID_SIZE_COL), 1, 0)+ \
                                jnp.where((ga[apple_locs[0]-2, apple_locs[1]]) & (apple_locs[0]-2 >=0), 1, 0) + \
                                jnp.where((ga[apple_locs[0]+2, apple_locs[1]]) & (apple_locs[0]+2 < self.GRID_SIZE_ROW), 1 ,0) + \
                                jnp.where((ga[apple_locs[0], apple_locs[1]-2]) & (apple_locs[1]-2 >=0), 1, 0) + \
                                jnp.where((ga[apple_locs[0], apple_locs[1]+2]) & (apple_locs[1]+2 < self.GRID_SIZE_COL), 1 ,0) + \
                                jnp.where((ga[apple_locs[0]-1, apple_locs[1]-1]) & (apple_locs[0]-1 >=0) & (apple_locs[1]-1 >=0), 1, 0) + \
                                jnp.where((ga[apple_locs[0]-1, apple_locs[1]+1]) & (apple_locs[0]-1 >=0) & (apple_locs[1]+1 < self.GRID_SIZE_COL), 1, 0) + \
                                jnp.where((ga[apple_locs[0]+1, apple_locs[1]-1]) & (apple_locs[1]+1 < self.GRID_SIZE_COL) & (apple_locs[1]-1 >=0), 1, 0) + \
                                jnp.where((ga[apple_locs[0]+1, apple_locs[1]+1]) & (apple_locs[0]+1 < self.GRID_SIZE_ROW) & (apple_locs[1]+1 < self.GRID_SIZE_COL) , 1, 0)
                
                return apple_nums

            near_apple_nums = jax.vmap(count_apple)(self.SPAWNS_APPLE)
            
            # grid_apple = state.grid

            def regrow_apple(apple_locs, near_apple, prob, rate, hue, age, last_stage, ripen_len, ripen_draw, rot_draw):
                cell = grid_apple[apple_locs[0], apple_locs[1]]
                empty = cell == Items.empty
                # vanilla thresholds x the hidden speed of this cell (hue's order applied to the stage its last apple left at)
                base = self.REGROW_BASE[jnp.clip(3 - near_apple, 0, 3)]      # vanilla: 2.5% / 0.5% / 0.1% / 0 for >=3 / 2 / 1 / 0 hanging neighbours
                pending = empty & (age < 0)                                    # counting down after a rot
                grows = empty & ((prob < base * rate) | (age == -1))            # chance regrowth, or the rot countdown ran out
                hanging = is_apple(cell)
                new_age = jnp.where(hanging, age + 1, jnp.where(pending, age + 1, 0))
                rotten = hanging & (new_age >= NUM_RIPE_STAGES * ripen_len)
                stage = jnp.minimum(new_age // ripen_len, NUM_RIPE_STAGES - 1)
                ripened = APPLE_BASE + hue * NUM_RIPE_STAGES + stage
                new_cell = jnp.where(grows, APPLE_BASE + hue * NUM_RIPE_STAGES,
                                     jnp.where(hanging & ~rotten, ripened, jnp.where(hanging & rotten, Items.empty, cell)))
                new_age = jnp.where(rotten, -rot_draw, jnp.where(grows, 0, new_age))   # rot starts a countdown drawn from rot_regrow_range; a new apple starts at age 0
                new_last = jnp.where(rotten, NUM_RIPE_STAGES - 1, last_stage)      # a rotted apple counts as having left at over-ripe
                new_len = jnp.where(grows, ripen_draw, ripen_len)                   # a new apple draws its own steps per stage
                return new_cell.astype(jnp.int16), new_age.astype(jnp.int16), new_last.astype(jnp.int8), new_len.astype(jnp.int16)

            prob = jax.random.uniform(key, shape=(len(self.SPAWNS_APPLE),))
            # the per-apple draws use fold_in so the existing random stream is untouched: with degenerate ranges the env replays old logs bit for bit
            ripen_draw = jax.random.randint(jax.random.fold_in(key, 11), (len(self.SPAWNS_APPLE),), self.ripen_lo, self.ripen_hi + 1)
            rot_draw = jax.random.randint(jax.random.fold_in(key, 12), (len(self.SPAWNS_APPLE),), self.rot_lo, self.rot_hi + 1)
            new_apple, new_age, new_last, new_len = jax.vmap(regrow_apple)(self.SPAWNS_APPLE, near_apple_nums, prob, cell_rate, state.cell_hues, state.age, state.last_stage,
                                                                           state.ripen_len, ripen_draw, rot_draw)
            # a cell currently under an agent keeps the agent code (its apple was eaten on arrival)
            under_agent = grid_apple[self.SPAWNS_APPLE[:, 0], self.SPAWNS_APPLE[:, 1]] >= len(Items)
            new_apple = jnp.where(under_agent, grid_apple[self.SPAWNS_APPLE[:, 0], self.SPAWNS_APPLE[:, 1]], new_apple)
            new_age = jnp.where(under_agent, jnp.where(state.age < 0, jnp.minimum(state.age + 1, -1), 0), new_age)   # an occupied cell keeps its rot countdown (held at -1 until free)
            new_apple_grid = grid_apple.at[self.SPAWNS_APPLE[:, 0], self.SPAWNS_APPLE[:, 1]].set(new_apple[:])
            state = state.replace(grid=new_apple_grid, age=new_age, last_stage=new_last, ripen_len=jnp.where(under_agent, state.ripen_len, new_len))

            # moving all agents

            new_grid = state.grid.at[
                state.agent_locs[:, 0],
                state.agent_locs[:, 1]
            ].set(
                jnp.int16(Items.empty)
            )

            x, y = state.reborn_locs[:, 0], state.reborn_locs[:, 1]
            new_grid = new_grid.at[x, y].set(self._agents)
            state = state.replace(grid=new_grid)
            state = state.replace(agent_locs=state.reborn_locs)

            # state = state.replace(reborn_locs=state.agent_locs)

            key, subkey = jax.random.split(key)
            all_new_locs = jax.vmap(lambda p, a: jnp.int16(p + ROTATIONS[a]) % jnp.array([self.GRID_SIZE_ROW + 1, self.GRID_SIZE_COL + 1, 4], dtype=jnp.int16))(p=state.agent_locs, a=actions).reshape(-1, 3)

            agent_move = (actions == Actions.up) | (actions == Actions.down) | (actions == Actions.right) | (actions == Actions.left)
            all_new_locs = jax.vmap(lambda m, n, p: jnp.where(m, n + STEP_MOVE[p], n))(m=agent_move, n=all_new_locs, p=actions)
            
            all_new_locs = jax.vmap(
                jnp.clip,
                in_axes=(0, None, None)
            )(
                all_new_locs,
                jnp.array([0, 0, 0], dtype=jnp.int16),
                jnp.array(
                    [self.GRID_SIZE_ROW - 1, self.GRID_SIZE_COL - 1, 3],
                    dtype=jnp.int16
                ),
            ).reshape(-1, 3)

            # Block impassable cells (anything that is not empty/apple/an
            # agent stamp) BEFORE conflict resolution; cells currently
            # holding an agent (grid code >= len(Items)) stay passable so
            # trains/following can work.
            target_cells = state.grid[all_new_locs[:, 0], all_new_locs[:, 1]]
            blocked = ((target_cells != Items.empty) &
                       ~is_apple(target_cells) &
                       (target_cells < len(Items)))
            all_new_locs = jnp.where(blocked[:, None], state.agent_locs, all_new_locs)

            # Resolve agent-agent movement conflicts via the shared
            # resolver: same-target conflicts (non-mover priority, else
            # random winner), swaps blocked, trains allowed, cascades
            # reverted to a fixed point. Final (row, col) unique.
            key, move_key = jax.random.split(key)
            new_locs = resolve_movement(move_key, state.agent_locs, all_new_locs)

            # update inventories
            def coin_matcher(p: jnp.ndarray) -> jnp.ndarray:
                return jnp.array([is_apple(state.grid[p[0], p[1]])])

            apple_matches = jax.vmap(coin_matcher)(p=new_locs)
            picked_code = state.grid[new_locs[:, 0], new_locs[:, 1]].astype(jnp.int32)
            picked_hue = jnp.clip(apple_hue(picked_code), 0, self.num_hues - 1)
            picked_stage = jnp.clip(apple_stage(picked_code), 0, NUM_RIPE_STAGES - 1)
            own_value = state.values[jnp.arange(self.num_agents), picked_hue].astype(jnp.float32)
            multiplier = self.PAY_TABLE[order[picked_hue], picked_stage]   # the hidden per-hue pay order over the stages
            apple_value = (own_value * multiplier * apple_matches.reshape(-1)).reshape(-1, 1)
            # the eaten apple's cell is now the agent: reset its age and remember the stage it was eaten at (sets its regrowth speed)
            eaten_cell = jnp.zeros((self.GRID_SIZE_ROW, self.GRID_SIZE_COL), dtype=bool).at[new_locs[:, 0], new_locs[:, 1]].set(True)
            ate_grid = jnp.zeros((self.GRID_SIZE_ROW, self.GRID_SIZE_COL), dtype=bool).at[new_locs[:, 0], new_locs[:, 1]].set(apple_matches.reshape(-1))
            stage_grid = jnp.zeros((self.GRID_SIZE_ROW, self.GRID_SIZE_COL), dtype=jnp.int8).at[new_locs[:, 0], new_locs[:, 1]].set(picked_stage.astype(jnp.int8))
            sp_r, sp_c = self.SPAWNS_APPLE[:, 0], self.SPAWNS_APPLE[:, 1]
            state = state.replace(age=jnp.where(eaten_cell[sp_r, sp_c], 0, state.age),
                                  last_stage=jnp.where(ate_grid[sp_r, sp_c], stage_grid[sp_r, sp_c], state.last_stage))

            
            # rewards = jnp.zeros((self.num_agents, 1))
            # rewards = apple_value

            # single reward or sum reward

            # rewards_sum_all_agents = jnp.zeros((self.num_agents, 1))
            # rewards_sum = jnp.sum(rewards)
            # rewards_sum_all_agents += rewards_sum
            # rewards = rewards_sum_all_agents

            new_invs = state.agent_invs + apple_matches

            state = state.replace(
                agent_invs=new_invs
            )

            # update grid
            old_grid = state.grid

            new_grid = old_grid.at[
                state.agent_locs[:, 0],
                state.agent_locs[:, 1]
            ].set(
                jnp.int16(Items.empty)
            )
            x, y = new_locs[:, 0], new_locs[:, 1]
            new_grid = new_grid.at[x, y].set(self._agents)
            state = state.replace(grid=new_grid)

            # update agent locations
            state = state.replace(agent_locs=new_locs)

            reborn_players, state = _interact(key, state, actions)
            fired = (actions == Actions.zap_forward)
            state = state.replace(
                zap_wait=jnp.where(reborn_players.astype(bool), self.frames_till_respawn,
                                   jnp.maximum(state.zap_wait - 1, 0)).astype(jnp.int16),
                zap_cd=jnp.where(fired, self.zap_cooldown, jnp.maximum(state.zap_cd - 1, 0)).astype(jnp.int16),
            )

            # Occupancy-aware respawn: reborn agents are placed on spawn
            # cells not occupied by any survivor, so no overlap is possible.
            key, respawn_key = jax.random.split(key)
            new_re_locs = resolve_respawn(
                respawn_key, new_locs, reborn_players.astype(bool), self.SPAWNS_PLAYERS
            )
            state = state.replace(reborn_locs=new_re_locs)

            # Rewards are individual only: an apple pays the agent that ate it. There is deliberately no
            # common-reward mode -- summing everyone's apples would remove the social dilemma.
            if self.inequity_aversion:
                rewards = jnp.zeros((self.num_agents, 1))
                original_rewards = apple_value * self.num_agents
                if self.smooth_rewards:
                    should_smooth = (state.inner_t % 1) == 0
                    new_smooth_rewards = 0.99 * 0.01* state.smooth_rewards + original_rewards
                    rewards, disadvantageous, advantageous = self.get_inequity_aversion_rewards_immediate(new_smooth_rewards, state.inner_t, self.inequity_aversion_target_agents, self.inequity_aversion_alpha, self.inequity_aversion_beta)
                    state = state.replace(smooth_rewards=new_smooth_rewards)
                    info = {
                    "original_rewards": original_rewards.squeeze(),
                    "smooth_rewards": state.smooth_rewards.squeeze(),
                    "shaped_rewards": rewards.squeeze(),
                }
                else:
                    rewards, disadvantageous, advantageous = self.get_inequity_aversion_rewards_immediate(original_rewards, state.inner_t, self.inequity_aversion_target_agents, self.inequity_aversion_alpha, self.inequity_aversion_beta)
                    info = {
                    "original_rewards": original_rewards.squeeze(),
                    "shaped_rewards": rewards.squeeze(),
                }
            elif self.svo:
                rewards = jnp.zeros((self.num_agents, 1))
                original_rewards = apple_value * self.num_agents
                rewards, theta = self.get_svo_rewards(original_rewards, self.svo_w, self.svo_ideal_angle_degrees, self.svo_target_agents)
                info = {
                    "original_rewards": original_rewards.squeeze(),
                    "svo_theta": theta.squeeze(),
                    "shaped_rewards": rewards.squeeze(),
                }
            elif self.interest:
                rewards = jnp.zeros((self.num_agents, 1))
                original_rewards = apple_value * self.num_agents

                # Calculate current s_interest based on timestep
                current_s_interest = get_current_s_interest(timestep)
                original_flat = original_rewards.squeeze()

                # Each agent gets s * their_reward + (1-s)/(n-1) * sum_of_others
                total_reward = jnp.sum(original_flat)
                others_reward = total_reward - original_flat  # sum of all other agents' rewards

                rewards = (current_s_interest * original_flat +
                        (1 - current_s_interest) / (self.num_agents - 1) * others_reward).reshape(-1, 1)

                info = {
                    "original_rewards": original_rewards.squeeze(),
                    "shaped_rewards": rewards.squeeze(),
                    "s_interest": current_s_interest,
                }
            else:
                rewards = jnp.zeros((self.num_agents, 1))
                rewards = apple_value * self.num_agents
                info = {"original_rewards": rewards.squeeze(), "shaped_rewards": rewards.squeeze()}
            
            AppleCount = jnp.sum(is_apple(state.grid))
            info["AppleCount_info"] = jnp.zeros((self.num_agents, 1)).squeeze() + AppleCount
            info["trial"] = jnp.zeros((self.num_agents,), dtype=jnp.int32) + state.outer_t
            info["eaten"] = apple_matches.reshape(-1).astype(jnp.int32)
            info["eaten_hue"] = jnp.where(apple_matches.reshape(-1), picked_hue, -1).astype(jnp.int32)
            info["eaten_stage"] = jnp.where(apple_matches.reshape(-1), picked_stage, -1).astype(jnp.int32)
            
            
            state_nxt = State(
                agent_locs=state.agent_locs,
                agent_invs=state.agent_invs,
                inner_t=state.inner_t + 1,
                outer_t=state.outer_t,
                grid=state.grid,
                apples=state.apples,
                freeze=state.freeze,
                reborn_locs=state.reborn_locs,
                age=state.age,
                rule_encoding=state.rule_encoding,
                values=state.values,
                cell_hues=state.cell_hues,
                last_stage=state.last_stage,
                ripen_len=state.ripen_len,
                zap_cd=state.zap_cd,
                zap_wait=state.zap_wait,
            )

            # now calculate if done for inner or outer episode
            inner_t = state_nxt.inner_t
            outer_t = state_nxt.outer_t
            reset_inner = inner_t == num_inner_steps

            # trial boundary: re-lay the orchard, keep the hidden rules and the value table
            state_re = _reset_state(key, state_nxt.rule_encoding, state_nxt.values, state_nxt.cell_hues)

            state_re = state_re.replace(outer_t=outer_t + 1)
            state = jax.tree.map(
                lambda x, y: jnp.where(reset_inner, x, y),
                state_re,
                state_nxt,
            )
            outer_t = state.outer_t
            reset_outer = outer_t == num_outer_steps
            done = {f'{a}': reset_outer for a in self.agents}
            # done = [reset_outer for _ in self.agents]
            done["__all__"] = reset_outer

            obs = _get_obs(state)
            rewards = jnp.where(
                reset_inner,
                jnp.zeros_like(rewards, dtype=jnp.float32),
                rewards
            )


            return (
                obs,
                state,
                rewards.squeeze(),
                done,
                info,
            )

        def _reset_state(
            key: jnp.ndarray, rule_encoding=None, values=None, cell_hues=None
        ) -> State:
            key, subkey, rule_key, value_key = jax.random.split(key, 4)
            hue_key = jax.random.fold_in(value_key, 7)          # separate stream; leaves the existing key split untouched
            if cell_hues is None:
                if self.fixed_patch_hues is not None:
                    slot_hues = self.fixed_patch_hues
                elif self.random_patch_hues and self.patch_hues_with_replacement:
                    slot_hues = jax.random.randint(hue_key, (self.NUM_SLOTS,), 0, self.num_hues)
                elif self.random_patch_hues:
                    slot_hues = jax.random.permutation(hue_key, self.num_hues)[: self.NUM_SLOTS]
                else:
                    slot_hues = jnp.arange(self.NUM_SLOTS, dtype=jnp.int32)
                cell_hues = jnp.asarray(slot_hues, dtype=jnp.int32)[self.APPLE_SLOTS]
            ripen_len0 = jax.random.randint(jax.random.fold_in(key, 13), (len(self.SPAWNS_APPLE),), self.ripen_lo, self.ripen_hi + 1).astype(jnp.int16)
            if rule_encoding is None:
                if self.fixed_rules is not None:
                    from opensocialjax.environments.discovery_rules import encode_harvest_ruleset
                    rule_encoding = encode_harvest_ruleset(self.fixed_rules[0], self.fixed_rules[1])
                elif self.rule_pool is not None:
                    rule_encoding = self.rule_pool.sample(rule_key)
                else:
                    rule_encoding = sample_harvest_ruleset(rule_key, self.num_hues)
            if values is None:
                values = (self.fixed_values if self.fixed_values is not None else
                          jnp.broadcast_to(jax.random.randint(value_key, (1, self.num_hues), 1, self.value_levels + 1), (num_agents, self.num_hues)).astype(jnp.uint8))

            # Find the free spaces in the grid
            grid = jnp.zeros((self.GRID_SIZE_ROW, self.GRID_SIZE_COL), jnp.int16)

            # all_positions = jax.random.permutation(subkey, self.SPAWNS)
            # player_reborn_pos = 
            # total_items = num_agents + NUM_COIN_TYPES * self.NUM_COINS

            # Inside spawns first, then outside spawns; the two pools are
            # disjoint grid cells, so the concatenation has no duplicates
            # (the old code re-drew from a pool that already contained
            # inside_players_pos and could seat two agents on one cell).
            key, subkey2 = jax.random.split(key)
            inside_players_pos = jax.random.permutation(subkey, self.SPAWNS_PLAYER_IN)
            outside_players_pos = jax.random.permutation(subkey2, self.SPAWNS_PLAYERS)
            agent_pos = jnp.concatenate((inside_players_pos, outside_players_pos))[:num_agents]
            wall_pos = self.SPAWNS_WALL

            apple_pos = self.SPAWNS_APPLE

            grid = grid.at[
                apple_pos[:, 0],
                apple_pos[:, 1]
            ].set((APPLE_BASE + cell_hues * NUM_RIPE_STAGES + self.initial_stage).astype(jnp.int16))

            grid = grid.at[
                wall_pos[:, 0],
                wall_pos[:, 1]
            ].set(jnp.int16(Items.wall))


            player_dir = jax.random.randint(
                subkey, shape=(
                    num_agents,
                    ), minval=0, maxval=3, dtype=jnp.int8
            )

            agent_locs = jnp.array(
                [agent_pos[:, 0], agent_pos[:, 1], player_dir],
                dtype=jnp.int16
            ).T

            grid = grid.at[
                agent_locs[:, 0],
                agent_locs[:, 1]
            ].set(jnp.int16(self._agents))

            freeze = jnp.array(
                [[-1]*num_agents]*num_agents,
            dtype=jnp.int16
            )

            return State(
                agent_locs=agent_locs,
                agent_invs=jnp.array([(0,0)]*num_agents, dtype=jnp.int8),
                inner_t=0,
                outer_t=0,
                grid=grid,
                apples=apple_pos,

                freeze=freeze,
                reborn_locs = agent_locs,
                age=(self.initial_stage * ripen_len0).astype(jnp.int16),
                rule_encoding=jnp.asarray(rule_encoding, dtype=jnp.uint8),
                values=jnp.asarray(values, dtype=jnp.uint8),
                cell_hues=jnp.asarray(cell_hues, dtype=jnp.int32),
                last_stage=jnp.zeros((len(self.SPAWNS_APPLE),), dtype=jnp.int8),
                ripen_len=ripen_len0,
                zap_cd=jnp.zeros((num_agents,), dtype=jnp.int16),
                zap_wait=jnp.zeros((num_agents,), dtype=jnp.int16),
            )

        def reset(
            key: jnp.ndarray
        ) -> Tuple[jnp.ndarray, State]:
            state = _reset_state(key)
            obs = _get_obs(state)
            return obs, state
